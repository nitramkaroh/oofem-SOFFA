#
# Input checks of the IGA surface element in space (bspline3dsurfaceelement, BSpline3dSurfaceInterpolation):
# - a membrane on a bilinear patch runs;
# - the control points need three coordinates, and their number must match the knot vectors and degrees;
# - a surface needs two degrees, each >= 1;
# - coinciding control points (no tangent plane) must stop with an error instead of giving NaN;
# - only the membrane is implemented: the bending material (second gradient) is rejected, as are the
#   anisotropic surface material (3D Lagrange surface elements only) and the IGA clamp (planar curves only);
# - the cross section must be a simplesurfacecs, and only nlgeo 1 is implemented.
# The inputs are generated into a temporary directory, so nothing is written to tests/sm.
# All displacements are prescribed; the material is evaluated for the reactions.
# Run by ctest as: bash iga-surface3d-checks.sh <oofem executable>
#
OOFEM=$1
case "$OOFEM" in
    /* | ?:*) ;;
    *) OOFEM="$PWD/$OOFEM" ;;
esac
echo "target executable: $OOFEM"

WORK=$(mktemp -d) || exit 1
trap 'cd / && rm -rf "$WORK"' EXIT
cd "$WORK" || exit 1

# Nodes 1-4: a bilinear patch in the plane z = 0.5 x + 0.25 y; node 5 coincides with node 1, node 6 with node 3,
# node 7 has two coordinates only. Unused nodes only carry the prescribed displacements.
BILINEAR='bspline3dsurfaceelement 1 nodes 4 1 2 3 4 crosssect 1 knotvectoru 2 0 1 knotvectorv 2 0 1 degree 2 1 1 nip 4 nlgeo 1'
TWOCOORDS='bspline3dsurfaceelement 1 nodes 4 7 2 3 4 crosssect 1 knotvectoru 2 0 1 knotvectorv 2 0 1 degree 2 1 1 nip 4 nlgeo 1'
MISMATCH='bspline3dsurfaceelement 1 nodes 3 1 2 3 crosssect 1 knotvectoru 2 0 1 knotvectorv 2 0 1 degree 2 1 1 nip 4 nlgeo 1'
ONEDEGREE='bspline3dsurfaceelement 1 nodes 2 1 2 crosssect 1 knotvectoru 2 0 1 degree 1 1 nip 2 nlgeo 1'
DEGREE0='bspline3dsurfaceelement 1 nodes 2 1 3 crosssect 1 knotvectoru 2 0 1 knotvectorv 2 0 1 degree 2 0 1 nip 4 nlgeo 1'
COINCIDENT='bspline3dsurfaceelement 1 nodes 4 1 5 3 6 crosssect 1 knotvectoru 2 0 1 knotvectorv 2 0 1 degree 2 1 1 nip 4 nlgeo 1'
NLGEO0='bspline3dsurfaceelement 1 nodes 4 1 2 3 4 crosssect 1 knotvectoru 2 0 1 knotvectorv 2 0 1 degree 2 1 1 nip 4'
SURFACE_CS='simplesurfacecs 1 material 1'
BULK_CS='simplecs 1 thick 1.0 material 1'
MEMBRANE='surfacetensionmat 1 gamma1 0.5 mu 1.0 d 1.0'
BENDING='surfacetensionmat2 1 gamma1 0.5 omega1 1.0 d 1.0'
ANISO='anisosurfacetensionmat 1 gamma1 0.4 alpha1 0.15 alphas 0.2 mu 0.3 lambda 0.1 eta 0.17 beta 0.13 p_1 3 0.0 0.0 -1.0 p_2 3 0.0 0.0 1.0 d 1.0'
CLAMP='igaclampboundarycondition 4 loadTimeFunction 1 numel 1 locpos 0.0 bcknotspan 1 p 1.e8'

# $1 case name, $2 element record, $3 cross section record, $4 material record, $5 extra boundary condition (or empty)
write_input() {
    nbc=3
    [ -n "$5" ] && nbc=4
    cat > "$1.in" <<EOF
$1.out
IGA surface checks in 3D: $2 / $4 (generated by iga-surface3d-checks.sh)
StaticStructural nsteps 1 deltat 1.0 rtolv 1.e-11 maxiter 10 nmodules 0
domain 3d
OutputManager tstep_all dofman_all element_all
ndofman 7 nelem 1 ncrosssect 1 nmat 1 nbc $nbc nic 0 nltf 1 nset 2
node 1 coords 3 0.0 0.0 0.0
node 2 coords 3 1.0 0.0 0.5
node 3 coords 3 0.0 1.0 0.25
node 4 coords 3 1.0 1.0 0.75
node 5 coords 3 0.0 0.0 0.0
node 6 coords 3 0.0 1.0 0.25
node 7 coords 2 0.0 0.0
$2
$3
$4
BoundaryCondition 1 loadTimeFunction 1 dofs 2 1 2 values 2 0.0 0.0 set 1
BoundaryCondition 2 loadTimeFunction 1 dofs 1 3 values 1 0.0 set 1
BoundaryCondition 3 loadTimeFunction 1 dofs 1 1 values 1 0.1 set 2
$5
ConstantFunction 1 f(t) 1.0
Set 1 nodes 7 1 2 3 4 5 6 7
Set 2 nodes 2 2 4
EOF
}

failures=0

# The analysis must finish, write its results, and give no nonfinite numeric tokens.
expect_existing_run() {
    if ! "$OOFEM" -f "$1.in" > "$1.log" 2>&1; then
        echo "FAIL $1: should run"
        cat "$1.log"
        failures=$((failures + 1))
    elif [ ! -s "$1.out" ] || ! grep -q 'ANALYSIS FINISHED' "$1.log"; then
        echo "FAIL $1: missing results or unfinished analysis"
        cat "$1.log"
        failures=$((failures + 1))
    elif ! awk '
        function nonfinite(value) {
            value = tolower(value)
            if ( value ~ /^[+-]?(nan(\([^)]*\))?|inf(inity)?|1[.]#(inf|ind|qnan|snan))$/ ) return 1
            sub(/^[([]/, "", value)
            sub(/[),;]$/, "", value)
            return value ~ /^[+-]?(nan(\([^)]*\))?|inf(inity)?|1[.]#(inf|ind|qnan|snan))$/
        }
        { for ( i = 1; i <= NF; i++ ) if ( nonfinite($i) ) exit 1 }
        ' "$1.out"; then
        echo "FAIL $1: runs, but gives a nonfinite result"
        failures=$((failures + 1))
    else
        echo "OK   $1: runs"
    fi
}

expect_run() {
    write_input "$1" "$2" "$3" "$4" "$5"
    expect_existing_run "$1"
}

# Rectangular patch with representable area and gradients at disparate coordinate scales.
# Prescribe an affine stretch in x (or y for the extreme-aspect case) and check F at every point.
write_scaled_patch() {
    uy=${5:-0}
    f11=${6:-1.1}
    f22=${7:-1.0}
    cat > "$1.in" <<EOF
$1.out
IGA surface geometry range: affine stretch on a rectangular patch
StaticStructural nsteps 1 deltat 1.0 rtolv 1.e-11 maxiter 10 nmodules 1
errorcheck
domain 3d
OutputManager tstep_all dofman_all element_all
ndofman 4 nelem 1 ncrosssect 1 nmat 1 nbc 4 nic 0 nltf 1 nset 4
node 1 coords 3 0 0 0
node 2 coords 3 $2 0 0
node 3 coords 3 0 $3 0
node 4 coords 3 $2 $3 0
bspline3dsurfaceelement 1 nodes 4 1 2 3 4 crosssect 1 knotvectoru 2 0 1 knotvectorv 2 0 1 degree 2 1 1 nip 4 nlgeo 1
simplesurfacecs 1 material 1
surfacetensionmat 1 gamma1 0.5 mu 1 d 1
BoundaryCondition 1 loadTimeFunction 1 dofs 3 1 2 3 values 3 0 0 0 set 1
BoundaryCondition 2 loadTimeFunction 1 dofs 3 1 2 3 values 3 $4 0 0 set 2
BoundaryCondition 3 loadTimeFunction 1 dofs 3 1 2 3 values 3 0 $uy 0 set 3
BoundaryCondition 4 loadTimeFunction 1 dofs 3 1 2 3 values 3 $4 $uy 0 set 4
ConstantFunction 1 f(t) 1
Set 1 nodes 1 1
Set 2 nodes 1 2
Set 3 nodes 1 3
Set 4 nodes 1 4
#%BEGIN_CHECK% tolerance 1.e-10
#ELEMENT tStep 1 number 1 irule 0 gp 1 keyword 91 component 1 value $f11
#ELEMENT tStep 1 number 1 irule 0 gp 1 keyword 91 component 2 value $f22
#ELEMENT tStep 1 number 1 irule 0 gp 2 keyword 91 component 1 value $f11
#ELEMENT tStep 1 number 1 irule 0 gp 2 keyword 91 component 2 value $f22
#ELEMENT tStep 1 number 1 irule 0 gp 3 keyword 91 component 1 value $f11
#ELEMENT tStep 1 number 1 irule 0 gp 3 keyword 91 component 2 value $f22
#ELEMENT tStep 1 number 1 irule 0 gp 4 keyword 91 component 1 value $f11
#ELEMENT tStep 1 number 1 irule 0 gp 4 keyword 91 component 2 value $f22
#%END_CHECK%
EOF
}

# The analysis must stop with an error containing $6.
expect_error() {
    write_input "$1" "$2" "$3" "$4" "$5"
    if "$OOFEM" -f "$1.in" > "$1.log" 2>&1; then
        echo "FAIL $1: must be rejected, but the analysis finished"
        failures=$((failures + 1))
    elif grep -q "$6" "$1.log"; then
        echo "OK   $1: rejected"
    else
        echo "FAIL $1: failed for another reason"
        cat "$1.log"
        failures=$((failures + 1))
    fi
}

expect_run   membrane          "$BILINEAR"   "$SURFACE_CS" "$MEMBRANE" ''
expect_error two-coordinates   "$TWOCOORDS"  "$SURFACE_CS" "$MEMBRANE" '' 'needs three coordinates'
expect_error node-count        "$MISMATCH"   "$SURFACE_CS" "$MEMBRANE" '' 'control points'
expect_error one-degree        "$ONEDEGREE"  "$SURFACE_CS" "$MEMBRANE" '' 'degree size mismatch'
expect_error degree0           "$DEGREE0"    "$SURFACE_CS" "$MEMBRANE" '' 'degree >= 1 in both directions'
expect_error coincident-points "$COINCIDENT" "$SURFACE_CS" "$MEMBRANE" '' 'degenerate surface'
expect_error bending           "$BILINEAR"   "$SURFACE_CS" "$BENDING"  '' 'does not support the second gradient'
expect_error aniso             "$BILINEAR"   "$SURFACE_CS" "$ANISO"    '' 'needs a 3D Lagrange surface element'
expect_error clamp             "$BILINEAR"   "$SURFACE_CS" "$MEMBRANE" "$CLAMP" 'planar IGA curve element'
expect_error bulk-cs           "$BILINEAR"   "$BULK_CS"    "$MEMBRANE" '' 'SimpleSurfaceCrossSection'
expect_error nlgeo-zero        "$NLGEO0"     "$SURFACE_CS" "$MEMBRANE" '' 'only nlgeo 1'

write_scaled_patch small-square 1e-80 1e-80 1e-81
expect_existing_run small-square
write_scaled_patch large-square 1e80 1e80 1e79
expect_existing_run large-square
# Stretch along the short side: stretching the long side would overflow individual BH*u products,
# an assembly limitation distinct from the interpolation's representable reciprocal tangents.
write_scaled_patch extreme-aspect 1e160 1e-160 0 1e-161 1.0 1.1
expect_existing_run extreme-aspect

[ "$failures" -eq 0 ]
