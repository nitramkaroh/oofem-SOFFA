#
# Input checks of the surface membrane material and of the prestrained TriangularSurface:
# - the normal of TriangularSurface only checks the prestrain f0 (which determines the normal), so it needs prestrain
#   and has to be the normal that f0 maps to zero (up to the sign);
# - f0 has 9 components;
# - f0 and the normal have finite components, and the prestrain has a finite nonzero area ratio;
# - the keywords fixgamma, fixomega, fixalphas and aniso_ltf of earlier versions stop the analysis, because gamma_ltf
#   no longer scales all parameters (every parameter has its own <name>_ltf);
# - gaminit of earlier versions is accepted only as 0: an initial value of gamma belongs to its time function;
# - arclengthpar 2 (omega as the load parameter) needs the bending material surfacetensionmat2;
# - isolesurf is not implemented (it stops at input) and surface elements need nlgeo 1;
# - the anisotropic material takes the fibre direction from anisodir or from p_1 and p_2 (given together, meridional
#   needs them), the direction needs a part in the element plane, and prestrain stops the analysis.
# The inputs are generated into a temporary directory, so nothing is written to tests/sm.
# All displacements are prescribed; the material is evaluated for the reactions.
# Run by ctest as: bash surface-input-checks.sh <oofem executable>
#
OOFEM=$1
case "$OOFEM" in
    /* | ?:*) ;;
    *) OOFEM="$PWD/$OOFEM" ;;
esac
echo "target executable: $OOFEM"

WORK=$(mktemp -d) || exit 1
trap 'cd / && rm -rf "$WORK"' EXIT
cd "$WORK" || exit 1

TRIANGLE='triangularsurface 1 nodes 3 1 2 3 crosssect 1 nlgeo 1'
MEMBRANE='surfacetensionmat 1 gamma1 0.5 mu 0.2 d 1.0'
SURFACE_CS='simplesurfacecs 1 material 1'
# f0 in the order xx yy zz yz xz xy zy zx yx: the in-plane stretch diag(1.2, 0.9, 0) of the triangle in the plane z = 0
F0='prestrain 1 f0 9 1.2 0.9 0. 0. 0. 0. 0. 0. 0.'

# $1 case name, $2 element record, $3 material record
write_input() {
    cat > "$1.in" <<EOF
$1.out
Surface input checks: $2 / $3 (generated by surface-input-checks.sh)
StaticStructural nsteps 1 deltat 1.0 rtolv 1.e-11 maxiter 10 nmodules 0
domain 3d
OutputManager tstep_all dofman_all element_all
ndofman 3 nelem 1 ncrosssect 1 nmat 1 nbc ${NBC:-3} nic 0 nltf 1 nset 1
node 1 coords 3 0.0 0.0 0.0
node 2 coords 3 1.0 0.0 0.0
node 3 coords 3 0.0 1.0 0.0
$2
$SURFACE_CS
$3
${EXTRA_BC:-}
BoundaryCondition 1 loadTimeFunction 1 dofs 1 1 values 1 0.0 set 1
BoundaryCondition 2 loadTimeFunction 1 dofs 1 2 values 1 0.0 set 1
BoundaryCondition 3 loadTimeFunction 1 dofs 1 3 values 1 0.0 set 1
ConstantFunction 1 f(t) 1.0
Set 1 nodes 3 1 2 3
EOF
}

failures=0

# The analysis must finish and give no NaN.
expect_run() {
    write_input "$1" "$2" "$3"
    if ! "$OOFEM" -f "$1.in" > "$1.log" 2>&1; then
        echo "FAIL $1: should run"
        cat "$1.log"
        failures=$((failures + 1))
    elif grep -qi 'nan' "$1.out"; then
        echo "FAIL $1: runs, but gives NaN"
        failures=$((failures + 1))
    else
        echo "OK   $1: runs"
    fi
}

# The analysis must stop with an error containing $4.
expect_error() {
    write_input "$1" "$2" "$3"
    if "$OOFEM" -f "$1.in" > "$1.log" 2>&1; then
        echo "FAIL $1: must be rejected, but the analysis finished"
        failures=$((failures + 1))
    elif grep -q "$4" "$1.log"; then
        echo "OK   $1: rejected"
    else
        echo "FAIL $1: failed for another reason"
        cat "$1.log"
        failures=$((failures + 1))
    fi
}

expect_run   prestrain                 "$TRIANGLE $F0"                    "$MEMBRANE"
expect_run   prestrain-normal          "$TRIANGLE $F0 normal 3 0. 0. 1."  "$MEMBRANE"
expect_run   prestrain-normal-opposite "$TRIANGLE $F0 normal 3 0. 0. -2." "$MEMBRANE"
expect_run   prestrain-normal-large    "$TRIANGLE $F0 normal 3 0. 0. 1e308" "$MEMBRANE"
expect_run   prestrain-normal-small    "$TRIANGLE $F0 normal 3 0. 0. 1e-308" "$MEMBRANE"
expect_error prestrain-normal-wrong    "$TRIANGLE $F0 normal 3 1. 0. 1."  "$MEMBRANE" 'does not belong to the prestrain'
expect_error normal-zero               "$TRIANGLE $F0 normal 3 0. 0. 0."  "$MEMBRANE" 'finite nonzero vector'
expect_error normal-nan                "$TRIANGLE $F0 normal 3 nan 0. 1." "$MEMBRANE" 'finite nonzero vector'
expect_error normal-inf                "$TRIANGLE $F0 normal 3 inf 0. 1." "$MEMBRANE" 'finite nonzero vector'
expect_error normal-without-prestrain  "$TRIANGLE normal 3 0. 0. 1."      "$MEMBRANE" 'it needs prestrain'
expect_error f0-size                   "$TRIANGLE prestrain 1 f0 3 1.2 0.9 0." "$MEMBRANE" 'must have 9 components'
expect_error f0-nan                    "$TRIANGLE prestrain 1 f0 9 nan 0.9 0. 0. 0. 0. 0. 0. 0." "$MEMBRANE" 'must have finite components'
expect_error f0-inf                    "$TRIANGLE prestrain 1 f0 9 inf 0.9 0. 0. 0. 0. 0. 0. 0." "$MEMBRANE" 'must have finite components'
expect_error f0-area-overflow          "$TRIANGLE prestrain 1 f0 9 1e155 0.9 0. 0. 0. 0. 0. 0. 0." "$MEMBRANE" 'non-finite area ratio'
expect_error removed-fixgamma          "$TRIANGLE"                        "$MEMBRANE gamma_ltf 1 fixgamma 0" 'removed'
expect_error removed-fixalphas         "$TRIANGLE"                        "$MEMBRANE fixalphas 1"  'removed'
expect_run   gaminit-zero              "$TRIANGLE"                        "$MEMBRANE gamma_ltf 1 gaminit 0."
expect_error removed-gaminit           "$TRIANGLE"                        "$MEMBRANE gamma_ltf 1 gaminit 0.1" 'into that function'
expect_error membrane-arclength-omega  "$TRIANGLE"                        "$MEMBRANE arclengthpar 2" 'only surfacetensionmat2'
expect_error removed-arclenghtpar      "$TRIANGLE"                        "$MEMBRANE arclenghtpar 1" 'removed; use arclengthpar'
expect_error isolesurf-not-implemented "$TRIANGLE"                        'isolesurf 1 d 1.0 e 1.0 n 0.2 talpha 0.0' 'not implemented'
expect_error nlgeo-zero                'triangularsurface 1 nodes 3 1 2 3 crosssect 1' "$MEMBRANE" 'only nlgeo 1'
expect_error f0-without-prestrain      "$TRIANGLE f0 9 1 1 0 0 0 0 0 0 0" "$MEMBRANE" 'requires prestrain 1'
expect_error anisodir-zero             "$TRIANGLE anisodir 3 0 0 0"       "$MEMBRANE" 'finite nonzero vector'
expect_error anisodir-nan              "$TRIANGLE anisodir 3 nan 0 0"     "$MEMBRANE" 'finite nonzero vector'
expect_error anisodir-inf              "$TRIANGLE anisodir 3 inf 0 0"     "$MEMBRANE" 'finite nonzero vector'
ANISO='anisosurfacetensionmat 1 gamma1 0.5 mu 0.2 eta 0.3 beta 0.2 d 1.0'
AXIS='p_1 3 0 0 0 p_2 3 0 0 1'
expect_run   aniso-axis                "$TRIANGLE"                        "$ANISO $AXIS"
expect_run   aniso-axis-meridional     "$TRIANGLE"                        "$ANISO $AXIS meridional 1"
expect_run   aniso-anisodir-only       "$TRIANGLE anisodir 3 1 2 0.5"     "$ANISO"
expect_error aniso-no-direction        "$TRIANGLE"                        "$ANISO" 'give anisodir on the element'
expect_error aniso-p1-only             "$TRIANGLE"                        "$ANISO p_1 3 0 0 0" 'given together'
expect_error aniso-meridional-no-axis  "$TRIANGLE anisodir 3 1 2 0"       "$ANISO meridional 1" 'needs p_1 and p_2'
expect_error aniso-meridional-value    "$TRIANGLE"                        "$ANISO $AXIS meridional 2" 'must be 0 or 1'
expect_error aniso-anisodir-normal     "$TRIANGLE anisodir 3 0 0 1"       "$ANISO" 'no finite nonzero part in the element plane'
expect_error aniso-axis-in-plane       "$TRIANGLE"                        "$ANISO p_1 3 0 0 0 p_2 3 1 0 0" 'no fibre direction at a Gauss point'
expect_error aniso-prestrain           "$TRIANGLE $F0"                    "$ANISO $AXIS" 'does not support prestrain'
SURFACE_CS='simplecs 1 material 1' expect_error cross-section-type "$TRIANGLE" "$MEMBRANE" 'simplesurfacecs.*required'
expect_error material-type "$TRIANGLE" 'isole 1 d 1 e 1 n .2 talpha 0' 'HyperElasticSurfaceMaterial.*required'
NBC=4 EXTRA_BC='PointLoad 4 loadTimeFunction 1 ndofs 3 coords 3 .2 .2 0 Components 3 1 0 0' \
    expect_error point-load "$TRIANGLE bodyloads 1 4" "$MEMBRANE" 'PointLoad is not supported'

# Run an already generated input, including its analytic errorcheck rules.
expect_existing_run() {
    if "$OOFEM" -f "$1.in" > "$1.log" 2>&1; then
        echo "OK   $1: analytic checks passed"
    else
        echo "FAIL $1: analytic checks failed"
        cat "$1.log"
        failures=$((failures + 1))
    fi
}

# A tilted line with 3-component node coordinates: R = gamma integral(grad N) - b integral(N).
cat > line-body-load.in <<'EOF'
line-body-load.out
Tilted planar line with a global body force, 3-component input coordinates and global F output
StaticStructural nsteps 1 deltat 1 rtolv 1.e-11 maxiter 10 nmodules 1
errorcheck
domain 2dPlaneStress
OutputManager tstep_all dofman_all element_all
ndofman 2 nelem 1 ncrosssect 1 nmat 1 nbc 3 nic 0 nltf 1 nset 1
node 1 coords 3 0 0 0
node 2 coords 3 3 4 0
lineplanestrainsurface 1 nodes 2 1 2 crosssect 1 nlgeo 1 bodyloads 1 3
simplesurfacecs 1 material 1
surfacetensionmat 1 gamma1 .5 d 1
BoundaryCondition 1 loadTimeFunction 1 dofs 1 1 values 1 0 set 1
BoundaryCondition 2 loadTimeFunction 1 dofs 1 2 values 1 0 set 1
DeadWeight 3 loadTimeFunction 1 Components 2 .1 .2
ConstantFunction 1 f(t) 1
Set 1 nodes 2 1 2
#%BEGIN_CHECK% tolerance 1.e-9
#REACTION tStep 1 number 1 dof 1 value -.55
#REACTION tStep 1 number 1 dof 2 value -.9
#REACTION tStep 1 number 2 dof 1 value .05
#REACTION tStep 1 number 2 dof 2 value -.1
#ELEMENT tStep 1 number 1 irule 0 gp 1 keyword 156 component 1 value .36
#ELEMENT tStep 1 number 1 irule 0 gp 1 keyword 156 component 2 value .64
#ELEMENT tStep 1 number 1 irule 0 gp 1 keyword 156 component 3 value 1
#ELEMENT tStep 1 number 1 irule 0 gp 1 keyword 156 component 6 value .48
#ELEMENT tStep 1 number 1 irule 0 gp 1 keyword 156 component 9 value .48
#%END_CHECK%
EOF
expect_existing_run line-body-load

# The same spatial frame must be used for f0, its normal and output F, independently of nodal lcs.
# In the local (a,b,n) frame F0=[[1.2,.3,0],[0,.9,0],[0,0,0]], a=(.6,.8,0), b=(0,0,1).
# The nonsymmetric shear makes a wrong transpose or a second application of F0 observable.
cat > prestrain-frame.in <<'EOF'
prestrain-frame.out
Tilted prestrained triangle with nodal lcs: global deformation gradient includes F0 exactly once
StaticStructural nsteps 1 deltat 1 rtolv 1.e-11 maxiter 10 nmodules 1
errorcheck
domain 3d
OutputManager tstep_all dofman_all element_all
ndofman 3 nelem 1 ncrosssect 1 nmat 1 nbc 3 nic 0 nltf 1 nset 1
node 1 coords 3 0 0 0 lcs 6 0 0 1 0 1 0
node 2 coords 3 .6 .8 0
node 3 coords 3 0 0 1
triangularsurface 1 nodes 3 1 2 3 crosssect 1 nlgeo 1 prestrain 1 f0 9 .432 .768 .9 .24 .18 .576 0 0 .576 normal 3 .8 -.6 0
simplesurfacecs 1 material 1
surfacetensionmat 1 gamma1 .5 d 1
BoundaryCondition 1 loadTimeFunction 1 dofs 1 1 values 1 0 set 1
BoundaryCondition 2 loadTimeFunction 1 dofs 1 2 values 1 0 set 1
BoundaryCondition 3 loadTimeFunction 1 dofs 1 3 values 1 0 set 1
ConstantFunction 1 f(t) 1
Set 1 nodes 3 1 2 3
#%BEGIN_CHECK% tolerance 1.e-9
#ELEMENT tStep 1 number 1 irule 0 gp 1 keyword 156 component 1 value .432
#ELEMENT tStep 1 number 1 irule 0 gp 1 keyword 156 component 2 value .768
#ELEMENT tStep 1 number 1 irule 0 gp 1 keyword 156 component 3 value .9
#ELEMENT tStep 1 number 1 irule 0 gp 1 keyword 156 component 4 value .24
#ELEMENT tStep 1 number 1 irule 0 gp 1 keyword 156 component 5 value .18
#ELEMENT tStep 1 number 1 irule 0 gp 1 keyword 156 component 6 value .576
#ELEMENT tStep 1 number 1 irule 0 gp 1 keyword 156 component 7 value 0
#ELEMENT tStep 1 number 1 irule 0 gp 1 keyword 156 component 8 value 0
#ELEMENT tStep 1 number 1 irule 0 gp 1 keyword 156 component 9 value .576
#%END_CHECK%
EOF
expect_existing_run prestrain-frame

cat > quad-bending.in <<'EOF'
quad-bending.out
C0 quadrilateral must reject a material which requires a second gradient
StaticStructural nsteps 1 deltat 1 nmodules 0
domain 3d
OutputManager tstep_all dofman_all
ndofman 4 nelem 1 ncrosssect 1 nmat 1 nbc 3 nic 0 nltf 1 nset 1
node 1 coords 3 0 0 0
node 2 coords 3 .6 .8 0
node 3 coords 3 .6 .8 1
node 4 coords 3 0 0 1
quadsurface 1 nodes 4 1 2 3 4 crosssect 1 nlgeo 1
simplesurfacecs 1 material 1
surfacetensionmat2 1 gamma1 .5 omega1 1 d 1
BoundaryCondition 1 loadTimeFunction 1 dofs 1 1 values 1 0 set 1
BoundaryCondition 2 loadTimeFunction 1 dofs 1 2 values 1 0 set 1
BoundaryCondition 3 loadTimeFunction 1 dofs 1 3 values 1 0 set 1
ConstantFunction 1 f(t) 1
Set 1 nodes 4 1 2 3 4
EOF
if "$OOFEM" -f quad-bending.in > quad-bending.log 2>&1; then
    echo 'FAIL quad-bending: must be rejected'
    failures=$((failures + 1))
elif grep -q 'second gradient' quad-bending.log; then
    echo 'OK   quad-bending: rejected'
else
    echo 'FAIL quad-bending: failed for another reason'
    cat quad-bending.log
    failures=$((failures + 1))
fi

# Neither an axis control point nor a zero nodal radius is forbidden; a zero integration-point radius is.
sed -e '1s/.*/axis-radius-zero.out/' -e 's/lineplanestrainsurface/axilinesurface/' \
    -e 's/node 2 coords 3 3 4 0/node 2 coords 3 0 1 0/' line-body-load.in > axis-radius-zero.in
if "$OOFEM" -f axis-radius-zero.in > axis-radius-zero.log 2>&1; then
    echo 'FAIL axis-radius-zero: must be rejected'
    failures=$((failures + 1))
elif grep -q 'reference radius must be finite and positive' axis-radius-zero.log; then
    echo 'OK   axis-radius-zero: rejected'
else
    echo 'FAIL axis-radius-zero: failed for another reason'
    cat axis-radius-zero.log
    failures=$((failures + 1))
fi

[ "$failures" -eq 0 ]
