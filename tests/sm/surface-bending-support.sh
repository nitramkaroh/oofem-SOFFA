#
# Surface material surfacetensionmat2 supports bending (omega1 != 0) only on IGA surface
# elements of degree at least 2, which provide the second gradient. On any other element the
# analysis must stop with an error, however small omega1 is; omega1 = 0 must run, and a
# small omega1 must run on an IGA element of degree 2.
# The inputs are generated into a temporary directory, so nothing is written to tests/sm.
# All displacements are prescribed; the material is evaluated for the reactions.
# Run by ctest as: bash surface-bending-support.sh <oofem executable>
#
OOFEM=$1
case "$OOFEM" in
    /* | ?:*) ;;
    *) OOFEM="$PWD/$OOFEM" ;;
esac
echo "target executable: $OOFEM"

WORK=$(mktemp -d) || exit 1
trap 'cd / && rm -rf "$WORK"' EXIT
cd "$WORK" || exit 1

# Node 2 (the middle control point) is used only by the degree-2 element.
LAGRANGE='lineplanestrainsurface 1 nodes 2 1 3 crosssect 1 nlgeo 1'
IGA_DEGREE1='bsplineplanestrainsurfaceelement 1 nodes 2 1 3 crosssect 1 knotvectoru 2 0 1 degree 1 1 nip 2 nlgeo 1'
IGA_DEGREE2='bsplineplanestrainsurfaceelement 1 nodes 3 1 2 3 crosssect 1 knotvectoru 2 0 1 degree 1 2 nip 3 nlgeo 1'
MESSAGE='needs an IGA surface element of degree at least 2'

# $1 case name, $2 element record, $3 omega1
write_input() {
    cat > "$1.in" <<EOF
$1.out
Bending support of surfacetensionmat2, omega1 = $3 (generated by surface-bending-support.sh)
StaticStructural nsteps 1 deltat 1.0 rtolv 1.e-11 maxiter 10 nmodules 0
domain 2dPlaneStress
OutputManager tstep_all dofman_all element_all
ndofman 3 nelem 1 ncrosssect 1 nmat 1 nbc 3 nic 0 nltf 1 nset 3
node 1 coords 2 0.0 0.0
node 2 coords 2 0.5 0.0
node 3 coords 2 1.0 0.0
$2
simplesurfacecs 1 material 1
surfacetensionmat2 1 gamma1 0.5 omega1 $3 d 1.0
BoundaryCondition 1 loadTimeFunction 1 dofs 1 1 values 1 0.0 set 1
BoundaryCondition 2 loadTimeFunction 1 dofs 1 2 values 1 0.0 set 2
BoundaryCondition 3 loadTimeFunction 1 dofs 1 2 values 1 1.0 set 3
ConstantFunction 1 f(t) 1.0
Set 1 nodes 3 1 2 3
Set 2 nodes 2 1 2
Set 3 nodes 1 3
EOF
}

failures=0

# The analysis must finish.
expect_run() {
    write_input "$1" "$2" "$3"
    if "$OOFEM" -f "$1.in" > "$1.log" 2>&1; then
        echo "OK   $1: omega1 = $3 runs"
    else
        echo "FAIL $1: omega1 = $3 should run"
        cat "$1.log"
        failures=$((failures + 1))
    fi
}

# The analysis must stop with the bending support error.
expect_error() {
    write_input "$1" "$2" "$3"
    if "$OOFEM" -f "$1.in" > "$1.log" 2>&1; then
        echo "FAIL $1: omega1 = $3 must be rejected, but the analysis finished"
        failures=$((failures + 1))
    elif grep -q "$MESSAGE" "$1.log"; then
        echo "OK   $1: omega1 = $3 rejected"
    else
        echo "FAIL $1: omega1 = $3 failed for another reason"
        cat "$1.log"
        failures=$((failures + 1))
    fi
}

expect_run   lagrange-zero           "$LAGRANGE"    0
expect_error lagrange-small          "$LAGRANGE"    1e-9
expect_error lagrange-small-negative "$LAGRANGE"    -1e-9
expect_error iga-degree1-small       "$IGA_DEGREE1" 1e-9
expect_run   iga-degree2-small       "$IGA_DEGREE2" 1e-9

[ "$failures" -eq 0 ]
