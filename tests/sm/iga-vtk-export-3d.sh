#
# VTK export (vtkxml) of IGA patches with three parametric directions (nurbs3delement),
# IGAElement::giveCompositeExportData:
# - a NURBS half annulus: u along the half circle (two quarter-circle knot spans, a double knot in the middle,
#   the weights 1, sqrt(2)/2, 1), v the radius from 1 to 2, w the height from 0 to 0.5. With numexp 3 it must
#   give 54 points and 16 hexahedra (VTK type 12), every point on the exact geometry (the rational quadratic
#   arc at its u, the radius 1 + v, the height 0.5 w) and the displacement (0.1, -0.2, 0.3) at every point;
# - this parametrization (u counterclockwise, v outward, w up) is left-handed, so the hexahedra must be
#   written with the reversed vertex order: in the VTK convention (the base 0-1-2-3 counterclockwise seen from
#   4-5-6-7) the Jacobian of the trilinear map of every cell must be positive at its corners, its 2 x 2 x 2
#   Gauss points and its centre. The same half annulus with the radius running inward (right-handed) must give
#   valid cells as well, with the usual vertex order. Neither may warn;
# - without numexp (default 2) only the corners of the knot spans are exported: 16 points and 2 hexahedra;
# - a twisted solid (CODEX-059): one knot span, cubic in w, whose cross-section turns by 180 degrees from the
#   bottom to the top, with a changing scale and without it. Its Jacobian is positive everywhere, but numexp 2
#   joins only the bottom and the top face, so the single hexahedron is tangled (a negative volume although
#   the Jacobian is positive at all corners) or pinched to a line in the middle: the export must warn, once in
#   two time steps. numexp 3 must give 8 valid hexahedra and no warning;
# - an internal variable is rejected, as for the other IGA elements without it.
# The coordinates are read from the complete Points array and all checked values must be decimal numbers.
# The inputs are generated into a temporary directory, so nothing is written to tests/sm.
# Run by ctest as: bash iga-vtk-export-3d.sh <oofem executable>
#
OOFEM=$1
case "$OOFEM" in
    /* | ?:*) ;;
    *) OOFEM="$PWD/$OOFEM" ;;
esac
echo "target executable: $OOFEM"

WORK=$(mktemp -d) || exit 1
trap 'cd / && rm -rf "$WORK"' EXIT
cd "$WORK" || exit 1

# Control points of the half annulus, u index fastest: u along the half circle (1, 0), (1, 1), (0, 1),
# (-1, 1), (-1, 0) times the radius, v the radius ($1, then $2), w the height (0, then 0.5).
annulus_nodes() {
    awk -v r0="$1" -v r1="$2" 'BEGIN {
        split("1 1 0 -1 -1", cx, " "); split("0 1 1 1 0", cy, " ")
        k = 0
        for ( iw = 0; iw <= 1; iw++ ) for ( iv = 0; iv <= 1; iv++ ) for ( iu = 1; iu <= 5; iu++ ) {
            r = iv ? r1 : r0
            printf "node %d coords 3 %g %g %g\n", ++k, r * cx[iu], r * cy[iu], 0.5 * iw
        }
    }'
}

WEIGHTS=$(for i in 1 2 3 4; do printf '1 0.7071067811865476 1 0.7071067811865476 1 '; done)
SOLID="nurbs3delement 1 crossSect 1 nodes 20 $(seq -s ' ' 1 20) weights 20 $WEIGHTS knotvectoru 3 0 0.5 1 knotmultiplicityu 3 3 2 3 knotvectorv 2 0 1 knotmultiplicityv 2 2 2 knotvectorw 2 0 1 knotmultiplicityw 2 2 2 degree 3 2 1 1 nip 8"

# Control points of the twisted solid (degrees 1, 1, 3, all weights 1), the exact polynomial map
#   x = a d1 u - b d2 v,  y = b d1 u + a d2 v,  z = w,  a = 1 - 2w,  b = 4w (1 - w),  d1 = 1 + $1 w,  d2 = 1 + $2 w,
# with the Jacobian (a^2 + b^2) d1 d2 > 0 for the used $1, $2; the cubic polynomials in w are given by their
# Bernstein coefficients (c0, c0 + c1/3, c0 + 2 c1/3 + c2/3, c0 + c1 + c2 + c3 for c0 + c1 w + c2 w^2 + c3 w^3).
twisted_nodes() {
    awk -v s1="$1" -v s2="$2" '
        function bern(c0, c1, c2, c3, k) { return k == 0 ? c0 : k == 1 ? c0 + c1 / 3 : k == 2 ? c0 + 2 * c1 / 3 + c2 / 3 : c0 + c1 + c2 + c3 }
        BEGIN {
            n = 0
            for ( k = 0; k <= 3; k++ ) {
                ad1 = bern(1, s1 - 2, -2 * s1, 0, k); ad2 = bern(1, s2 - 2, -2 * s2, 0, k)
                bd1 = bern(0, 4, 4 * s1 - 4, -4 * s1, k); bd2 = bern(0, 4, 4 * s2 - 4, -4 * s2, k)
                for ( j = 0; j <= 1; j++ ) for ( i = 0; i <= 1; i++ )
                    printf "node %d coords 3 %.17g %.17g %.17g\n", ++n, i * ad1 - j * bd2, i * bd1 + j * ad2, k / 3
            }
        }'
}
TWISTED="nurbs3delement 1 crossSect 1 nodes 16 $(seq -s ' ' 1 16) weights 16 $(for i in $(seq 16); do printf '1 '; done)knotvectoru 2 0 1 knotvectorv 2 0 1 knotvectorw 2 0 1 degree 3 1 1 3 nip 27"

# $1 case name, $2 vtkxml record, $3 element record, $4 node records, $5 number of time steps (default 1); the
# rigid translation (0.1, -0.2, 0.3) prescribed at all the control points
write_input() {
    nodes=$(printf '%s\n' "$4" | grep -c '^node')
    cat > "$1.in" <<EOF
$1.out
IGA VTK export check of a 3D patch (generated by iga-vtk-export-3d.sh)
StaticStructural nsteps ${5:-1} deltat 1.0 rtolv 1.e-11 maxiter 10 nmodules 1
$2
domain 3d
OutputManager tstep_all dofman_all
ndofman $nodes nelem 1 ncrosssect 1 nmat 1 nbc 3 nic 0 nltf 1 nset 1
$4
$3
SimpleCS 1 material 1
IsoLE 1 d 0. E 1.0 n 0.2 tAlpha 0.0
BoundaryCondition 1 loadTimeFunction 1 dofs 1 1 values 1 0.1 set 1
BoundaryCondition 2 loadTimeFunction 1 dofs 1 2 values 1 -0.2 set 1
BoundaryCondition 3 loadTimeFunction 1 dofs 1 3 values 1 0.3 set 1
ConstantFunction 1 f(t) 1.0
Set 1 nodes $nodes $(seq -s ' ' 1 "$nodes")
EOF
}

failures=0
fail() {
    echo "FAIL $1"
    failures=$((failures + 1))
}

# Values of the data array whose opening tag contains $2 (one array per line, as vtkxml writes it), one per line.
array() {
    awk -v key="$2" 'index($0, key) { sub(/^[^>]*>/, ""); sub(/<.*$/, ""); n = split($0, v, " "); for ( i = 1; i <= n; i++ ) print v[i] }' "$1"
}

# A decimal number (vtkxml writes no NaN or infinity for valid results).
NUMBER='^[+-]?([0-9]+([.][0-9]*)?|[.][0-9]+)([eE][+-]?[0-9]+)?$'

# The complete coordinate array of the Points section, not other three-component arrays.
point_array() {
    awk '
        /<Points>/ { points = 1; next }
        /<\/Points>/ { points = 0 }
        points && /<DataArray/ {
            sub(/^[^>]*>/, ""); sub(/<.*$/, "")
            n = split($0, v, " "); for ( i = 1; i <= n; i++ ) print v[i]
        }' "$1"
}

# The number of hexahedra (VTK order, the points file $1 and the connectivity file $2) whose trilinear map has a
# Jacobian that is not positive at the 8 Gauss points and the centre or negative at a corner; -1 if a value is
# not a decimal number.
invalid_hexahedra() {
    awk -v num="$NUMBER" '
        function jac(t1, t2, t3,    a, d, i, t, f, df, dn, J) {
            t[1] = t1; t[2] = t2; t[3] = t3
            for ( i = 1; i <= 3; i++ ) for ( d = 1; d <= 3; d++ ) J[i, d] = 0
            for ( a = 0; a < 8; a++ ) {
                for ( d = 1; d <= 3; d++ ) { f[d] = cn[a, d] ? t[d] : 1 - t[d]; df[d] = cn[a, d] ? 1 : -1 }
                dn[1] = df[1] * f[2] * f[3]; dn[2] = f[1] * df[2] * f[3]; dn[3] = f[1] * f[2] * df[3]
                for ( i = 1; i <= 3; i++ ) for ( d = 1; d <= 3; d++ ) J[i, d] += dn[d] * x[vtx[a], i]
            }
            return J[1, 1] * (J[2, 2] * J[3, 3] - J[2, 3] * J[3, 2]) - J[1, 2] * (J[2, 1] * J[3, 3] - J[2, 3] * J[3, 1]) \
                 + J[1, 3] * (J[2, 1] * J[3, 2] - J[2, 2] * J[3, 1])
        }
        BEGIN {
            # local coordinates of the VTK vertices 0..7 in the unit cube, Gauss points of 2 x 2 x 2 integration
            split("0 1 1 0 0 1 1 0", c1, " "); split("0 0 1 1 0 0 1 1", c2, " "); split("0 0 0 0 1 1 1 1", c3, " ")
            for ( a = 0; a < 8; a++ ) { cn[a, 1] = c1[a + 1]; cn[a, 2] = c2[a + 1]; cn[a, 3] = c3[a + 1] }
            g[0] = 0.5 - 0.5 / sqrt(3); g[1] = 0.5 + 0.5 / sqrt(3)
        }
        $0 !~ num { bad = 1 }
        NR == FNR { x[int((NR - 1) / 3), (NR - 1) % 3 + 1] = $1; next }
        { conn[k++] = $1 }
        END {
            if ( bad || k == 0 || k % 8 ) { print -1; exit }
            invalid = 0
            for ( q = 0; q < k / 8; q++ ) {
                for ( a = 0; a < 8; a++ ) vtx[a] = conn[8 * q + a]
                ok = jac(0.5, 0.5, 0.5) > 0
                for ( a = 0; a < 8; a++ ) {
                    if ( jac(g[a % 2], g[int(a / 2) % 2], g[int(a / 4)]) <= 0 ) ok = 0
                    if ( jac(cn[a, 1], cn[a, 2], cn[a, 3]) < 0 ) ok = 0
                }
                if ( !ok ) invalid++
            }
            print invalid
        }' "$1" "$2"
}

# The warning of the export about hexahedra that do not follow the geometry.
WARNING='do not follow the geometry'

# Runs case $1; the analysis must finish and write one .vtu file, whose name is printed. It runs in a command
# substitution (a subshell), so it only returns 1 on failure and the caller counts it with run_failed.
run_vtu() {
    "$OOFEM" -f "$1.in" > "$1.log" 2>&1 || return 1
    [ -s "$1.out" ] && grep -q 'ANALYSIS FINISHED' "$1.log" || return 1
    vtu=$(ls "$1".out.m*.1.vtu 2> /dev/null | head -1)
    [ -n "$vtu" ] || return 1
    echo "$vtu"
}

run_failed() {
    fail "$1: should run and write a .vtu file"
    cat "$1.log"
}

# Check the complete topology arrays, including their lengths: empty arrays must not pass vacuously.
# $1 case, $2 .vtu file, $3 points, $4 cells, $5 VTK type, $6 vertices per cell.
check_topology() {
    grep -q "NumberOfPoints=\"$3\" NumberOfCells=\"$4\"" "$2" || fail "$1: expected $3 points and $4 cells"
    array "$2" 'Name="types"' |
        awk -v n="$4" -v t="$5" '$0 !~ /^[0-9]+$/ || $1 != t { bad = 1 } END { exit bad || NR != n }' ||
        fail "$1: expected $4 cell types equal to $5"
    array "$2" 'Name="offsets"' |
        awk -v n="$4" -v k="$6" '$0 !~ /^[0-9]+$/ || $1 != NR * k { bad = 1 } END { exit bad || NR != n }' ||
        fail "$1: invalid cell offsets"
    array "$2" 'Name="connectivity"' |
        awk -v n="$3" -v c="$4" -v k="$6" '
            $0 !~ /^[0-9]+$/ || $1 < 0 || $1 >= n { bad = 1 }
            { cell = int((NR - 1) / k); if ( seen[cell, $1]++ ) bad = 1 }
            END { exit bad || NR != c * k }' || fail "$1: invalid cell connectivity"
}

# Case $1, sampled with $2 points per knot span and direction, the radius 1 + v ($3 = out) or 2 - v ($3 = in):
# 2 $2^3 points and 2 ($2 - 1)^3 hexahedra, every point on the exact half annulus, the displacement
# (0.1, -0.2, 0.3) at every point, every cell valid and no warning.
check_solid() {
    before=$failures
    vtu=$(run_vtu "$1") || { run_failed "$1"; return; }
    points=$((2 * $2 * $2 * $2))
    cells=$((2 * ($2 - 1) * ($2 - 1) * ($2 - 1)))
    check_topology "$1" "$vtu" "$points" "$cells" 12 8
    point_array "$vtu" > "$1.points"
    array "$vtu" 'Name="connectivity"' > "$1.cells"

    # The point p of the knot span s has the grid indices (iu, iv, iw), u fastest; the first span is the
    # quarter circle from (1, 0) to (0, 1), the second one the same rotated by 90 degrees.
    awk -v n="$2" -v np="$points" -v dir="$3" -v num="$NUMBER" '
        $0 !~ num { bad = 1 }
        { c[NR] = $1 }
        END {
            if ( bad || NR != 3 * np ) exit 1
            s2 = sqrt(2) / 2; m = n * n * n
            for ( p = 0; p < np; p++ ) {
                s = int(p / m); r = p % m
                t = (r % n) / (n - 1); v = (int(r / n) % n) / (n - 1); w = int(r / (n * n)) / (n - 1)
                b0 = (1 - t)^2; b1 = 2 * t * (1 - t) * s2; b2 = t^2; d = b0 + b1 + b2
                ax = (b0 + b1) / d; ay = (b1 + b2) / d
                if ( s == 1 ) { tmp = ax; ax = -ay; ay = tmp }
                radius = (dir == "out") ? 1 + v : 2 - v
                e[1] = radius * ax; e[2] = radius * ay; e[3] = 0.5 * w
                for ( i = 1; i <= 3; i++ ) if ( (c[3 * p + i] - e[i])^2 > 1e-12 * (1 + e[i]^2) ) exit 1  # 7 digits
            }
        }' "$1.points" || fail "$1: a point is not on the half annulus"

    array "$vtu" 'Name="DisplacementVector"' |
        awk -v np="$points" -v num="$NUMBER" '$0 !~ num { bad = 1 }
             { e = (NR % 3 == 1) ? 0.1 : (NR % 3 == 2) ? -0.2 : 0.3; if ( ($1 - e)^2 > 1e-24 ) bad = 1 }
             END { exit bad || NR != 3 * np }' || fail "$1: displacement differs from (0.1, -0.2, 0.3)"

    [ "$(invalid_hexahedra "$1.points" "$1.cells")" = 0 ] || fail "$1: a hexahedron is not valid (wrong vertex order)"
    ! grep -q "$WARNING" "$1.log" || fail "$1: unexpected warning about the hexahedra"
    [ "$failures" -eq "$before" ] && echo "OK   $1: $points points, $cells hexahedra, positions, displacements and orientation"
}

# Case $1, the twisted solid with numexp 2 and two time steps: the analysis must finish and write its single
# hexahedron, with exactly one warning.
check_warning() {
    before=$failures
    vtu=$(run_vtu "$1") || { run_failed "$1"; return; }
    check_topology "$1" "$vtu" 8 1 12 8
    [ "$(grep -c "$WARNING" "$1.log")" -eq 1 ] || { fail "$1: expected exactly one warning about the hexahedra"; cat "$1.log"; }
    [ "$failures" -eq "$before" ] && echo "OK   $1: one warning, the coarse hexahedron does not follow the geometry"
}

# Case $1, the twisted solid with numexp 3: 27 points, 8 valid hexahedra and no warning.
check_valid() {
    before=$failures
    vtu=$(run_vtu "$1") || { run_failed "$1"; return; }
    check_topology "$1" "$vtu" 27 8 12 8
    point_array "$vtu" > "$1.points"
    array "$vtu" 'Name="connectivity"' > "$1.cells"
    [ "$(invalid_hexahedra "$1.points" "$1.cells")" = 0 ] || fail "$1: a hexahedron is not valid"
    ! grep -q "$WARNING" "$1.log" || fail "$1: unexpected warning about the hexahedra"
    [ "$failures" -eq "$before" ] && echo "OK   $1: 8 valid hexahedra, no warning"
}

# Case $1 must stop with an error containing $2.
expect_error() {
    if "$OOFEM" -f "$1.in" > "$1.log" 2>&1; then
        fail "$1: must be rejected, but the analysis finished"
    elif grep -q "$2" "$1.log"; then
        echo "OK   $1: rejected"
    else
        fail "$1: failed for another reason"
        cat "$1.log"
    fi
}

VTK_DISP='vtkxml tstep_all domain_all primvars 1 1 stype 1'
VTK_STRESS='vtkxml tstep_all domain_all primvars 1 1 vars 1 1 stype 1'

# left-handed: u counterclockwise, v outward, w up
write_input solid "$VTK_DISP" "$SOLID numexp 3" "$(annulus_nodes 1 2)"
check_solid solid 3 out

# right-handed: the radius runs inward
write_input solid-inward "$VTK_DISP" "$SOLID numexp 3" "$(annulus_nodes 2 1)"
check_solid solid-inward 3 in

# the default numexp 2: the corners of the knot spans
write_input solid-default "$VTK_DISP" "$SOLID" "$(annulus_nodes 1 2)"
check_solid solid-default 2 out

write_input solid-stress "$VTK_STRESS" "$SOLID numexp 3" "$(annulus_nodes 1 2)"
expect_error solid-stress 'is not supported by the VTK export'

# the twisted solid: numexp 2 (the default) must warn, once in two time steps; numexp 3 resolves it
write_input twisted-tangled "$VTK_DISP" "$TWISTED" "$(twisted_nodes -0.9 9)" 2
check_warning twisted-tangled
write_input twisted-pinched "$VTK_DISP" "$TWISTED" "$(twisted_nodes 0 0)" 2
check_warning twisted-pinched
write_input twisted-tangled-3 "$VTK_DISP" "$TWISTED numexp 3" "$(twisted_nodes -0.9 9)"
check_valid twisted-tangled-3
write_input twisted-pinched-3 "$VTK_DISP" "$TWISTED numexp 3" "$(twisted_nodes 0 0)"
check_valid twisted-pinched-3

[ "$failures" -eq 0 ]
