#
# NURBS surface in space (nurbs3dsurfaceelement, NURBS3dSurfaceInterpolation) as a surface of revolution:
# - a curved quadratic generatrix (two knot spans, x = radius, y = axis) turned by a quarter about the y axis, the
#   quarter circle being a quadratic NURBS with two knot spans (unit control points (1, 0), (1, t), (t, 1), (0, 1),
#   t = tan(pi/8), weights 1, w, w, 1, w = (1 + 1/sqrt(2))/2), against the axisymmetric IGA surface
#   (bsplineaxisymsurfaceelement) with the same generatrix: surfacetensionmat2 with all membrane terms and bending
#   (useh0 1) and the same axisymmetric displacement u_r e_r + u_y e_y prescribed at all control points (in 3D
#   exactly (u_r c, u_y, u_r s) at the control point (r c, y, r s)). The generalized reactions of the 3D model at
#   every control point of the generatrix, F_r = sum over the arc of f . (c, 0, s) and F_y = sum of f_y (the virtual
#   work of an axisymmetric variation), must be pi/2 times the reactions of the axisymmetric element (per radian);
#   with 6 x 6 Gauss points per knot span the quadrature of the arc length is exact to 1e-12 and the printed
#   reactions agree to 3e-11 (relative to the largest one);
# - only the ratios of the weights matter: all weights times 1e307 or 1e-300 give the same reactions (the weights
#   are divided by the largest one; without that the weighted second derivatives overflow at 1e307);
# - the VTK export points of a NURBS cylinder of radius 1 (one knot span, weights 1, 1/sqrt(2), 1) lie on the
#   circle, which a B-spline with the same control points does not;
# - the weights must be given, one for every control point, finite and positive, and the ratio of the smallest to
#   the largest one must be in the normal range of double.
# The inputs are generated into a temporary directory, so nothing is written to tests/sm.
# Run by ctest as: bash iga-nurbs-axisym-checks.sh <oofem executable>
#
OOFEM=$1
case "$OOFEM" in
    /* | ?:*) ;;
    *) OOFEM="$PWD/$OOFEM" ;;
esac
echo "target executable: $OOFEM"

WORK=$(mktemp -d) || exit 1
trap 'cd / && rm -rf "$WORK"' EXIT
cd "$WORK" || exit 1

failures=0
fail() {
    echo "FAIL $1"
    failures=$((failures + 1))
}

# Case $1 must finish (exit code 0 and ANALYSIS FINISHED).
run_ok() {
    "$OOFEM" -f "$1.in" > "$1.log" 2>&1 && grep -q 'ANALYSIS FINISHED' "$1.log" && [ -s "$1.out" ]
}

# Case $1 must stop with an error containing $2.
expect_error() {
    if "$OOFEM" -f "$1.in" > "$1.log" 2>&1; then
        fail "$1: must be rejected, but the analysis finished"
    elif grep -q "$2" "$1.log"; then
        echo "OK   $1: rejected"
    else
        fail "$1: failed for another reason"
        cat "$1.log"
    fi
}

# Reactions of the output file $1 as lines "node dof value".
reactions() {
    tr -d '\r' < "$1" | awk '$1 == "Node" && $3 == "iDof" && $5 == "reaction" { print $2, $4, $6 }'
}

MATERIAL='surfacetensionmat2 1 gamma1 0.4 alpha1 0.2 mu 0.5 lambda 0.6 alphas 0.3 omega1 0.7 useh0 1 d 1.0'
# generatrix control points (radius, axis) and the prescribed displacements (u_r, u_y)
R='1.0 1.35 0.95 1.15'
Y='0.0 0.35 0.75 1.1'
UR='0.10 -0.05 0.08 0.03'
UY='0.0 0.04 -0.02 0.06'
# unit quarter circle with two knot spans: points (c, s) and weights
C='1.0 1.0 0.41421356237309503 0.0'
S='0.0 0.41421356237309503 1.0 1.0'
W='1.0 0.8535533905932737 0.8535533905932737 1.0'

# axisymmetric generatrix, 6 Gauss points per knot span
{
    cat <<EOF
axi.out
axisymmetric IGA surface (generated by iga-nurbs-axisym-checks.sh)
StaticStructural nsteps 1 deltat 1.0 rtolv 1.e-11 maxiter 10 nmodules 0
domain 2dPlaneStress
OutputManager tstep_all dofman_all
ndofman 4 nelem 1 ncrosssect 1 nmat 1 nbc 4 nic 0 nltf 1 nset 4
EOF
    awk -v r="$R" -v y="$Y" -v ur="$UR" -v uy="$UY" 'BEGIN {
        split(r, R); split(y, Y); split(ur, UR); split(uy, UY)
        for ( i = 1; i <= 4; i++ ) printf "node %d coords 2 %s %s\n", i, R[i], Y[i]
        print "bsplineaxisymsurfaceelement 1 nodes 4 1 2 3 4 crosssect 1 knotvectoru 3 0.0 0.4 1.0 degree 1 2 nip 6 nlgeo 1"
        print "simplesurfacecs 1 material 1"
        print "'"$MATERIAL"'"
        for ( i = 1; i <= 4; i++ ) printf "BoundaryCondition %d loadTimeFunction 1 dofs 2 1 2 values 2 %s %s set %d\n", i, UR[i], UY[i], i
        print "ConstantFunction 1 f(t) 1.0"
        for ( i = 1; i <= 4; i++ ) printf "Set %d nodes 1 %d\n", i, i
    }'
} > axi.in

# the same generatrix turned by a quarter, 6 x 6 Gauss points per knot span; node j*4 + i: arc point j, generatrix i
{
    cat <<EOF
s3d.out
NURBS surface of revolution (generated by iga-nurbs-axisym-checks.sh)
StaticStructural nsteps 1 deltat 1.0 rtolv 1.e-11 maxiter 10 nmodules 0
domain 3d
OutputManager tstep_all dofman_all
ndofman 16 nelem 1 ncrosssect 1 nmat 1 nbc 16 nic 0 nltf 1 nset 16
EOF
    awk -v r="$R" -v y="$Y" -v ur="$UR" -v uy="$UY" -v c="$C" -v s="$S" -v w="$W" 'BEGIN {
        split(r, R); split(y, Y); split(ur, UR); split(uy, UY); split(c, Cc); split(s, Ss); split(w, Ww)
        for ( j = 1; j <= 4; j++ ) for ( i = 1; i <= 4; i++ )
            printf "node %d coords 3 %.17g %s %.17g\n", (j - 1) * 4 + i, R[i] * Cc[j], Y[i], R[i] * Ss[j]
        nodes = ""; weights = ""
        for ( j = 1; j <= 4; j++ ) for ( i = 1; i <= 4; i++ ) { nodes = nodes " " (j - 1) * 4 + i; weights = weights " " Ww[j] }
        print "nurbs3dsurfaceelement 1 nodes 16" nodes " crosssect 1 knotvectoru 3 0.0 0.4 1.0 knotvectorv 3 0.0 0.5 1.0 degree 2 2 2 nip 36 nlgeo 1 weights 16" weights
        print "simplesurfacecs 1 material 1"
        print "'"$MATERIAL"'"
        for ( j = 1; j <= 4; j++ ) for ( i = 1; i <= 4; i++ ) {
            a = (j - 1) * 4 + i
            printf "BoundaryCondition %d loadTimeFunction 1 dofs 3 1 2 3 values 3 %.17g %s %.17g set %d\n", a, UR[i] * Cc[j], UY[i], UR[i] * Ss[j], a
        }
        print "ConstantFunction 1 f(t) 1.0"
        for ( a = 1; a <= 16; a++ ) printf "Set %d nodes 1 %d\n", a, a
    }'
} > s3d.in

if run_ok axi && run_ok s3d; then
    { reactions axi.out | sed 's/^/axi /'; reactions s3d.out | sed 's/^/s3d /'; } |
        awk -v c="$C" -v s="$S" -v num='^[+-]?([0-9]+([.][0-9]*)?|[.][0-9]+)([eE][+-]?[0-9]+)?$' '
            BEGIN { split(c, Cc); split(s, Ss); pi2 = atan2(1, 0) }
            $4 !~ num { bad = 1 }
            $1 == "axi" { ra[$2, $3] = $4; na++ }
            $1 == "s3d" { j = int(($2 - 1) / 4) + 1; i = ($2 - 1) % 4 + 1; n3++
                          if ( $3 == 1 ) fr[i] += $4 * Cc[j]; else if ( $3 == 3 ) fr[i] += $4 * Ss[j]; else fy[i] += $4 }
            END {
                if ( bad || na != 8 || n3 != 48 ) exit 1
                for ( i = 1; i <= 4; i++ ) {
                    er = pi2 * ra[i, 1]; ey = pi2 * ra[i, 2]
                    d = fr[i] - er; if ( d < 0 ) d = -d; if ( d > dmax ) dmax = d
                    d = fy[i] - ey; if ( d < 0 ) d = -d; if ( d > dmax ) dmax = d
                    if ( er < 0 ) er = -er; if ( ey < 0 ) ey = -ey
                    if ( er > scale ) scale = er; if ( ey > scale ) scale = ey
                }
                printf "     generalized reactions: max |3D - pi/2 axi| = %.2e, relative %.2e\n", dmax, dmax / scale
                exit !(scale > 0.1 && dmax <= 1e-9 * scale)
            }' && echo "OK   axisymmetric: generalized reactions = pi/2 x axisymmetric" ||
        fail "axisymmetric: generalized reactions of the 3D model differ from pi/2 x the axisymmetric ones"
else
    fail "axisymmetric: both models must run"
    cat axi.log s3d.log
fi

# the 3D model with all weights times a common factor: the reactions of s3d (to the printed precision)
for factor in 1e307 1e-300; do
    awk -v f="$factor" 'NR == 1 { print "s3d-" f ".out"; next }
        $1 == "nurbs3dsurfaceelement" {
            for ( k = 1; k <= NF; k++ ) if ( $k == "weights" ) {
                for ( m = k + 2; m <= k + 1 + $(k + 1); m++ ) $m = sprintf("%.17g", $m * f)
                break
            }
        }
        { print }' s3d.in > "s3d-$factor.in"
    if [ "$(grep '^nurbs3dsurfaceelement' s3d.in)" != "$(grep '^nurbs3dsurfaceelement' "s3d-$factor.in")" ] &&
        run_ok "s3d-$factor"; then
        { reactions s3d.out | sed 's/^/a /'; reactions "s3d-$factor.out" | sed 's/^/b /'; } |
            awk -v f="$factor" -v num='^[+-]?([0-9]+([.][0-9]*)?|[.][0-9]+)([eE][+-]?[0-9]+)?$' '
                $4 !~ num { bad = 1 }
                $1 == "a" { r[$2 " " $3] = $4; na++ }
                $1 == "b" { s[$2 " " $3] = $4; nb++ }
                END {
                    if ( bad || na != 48 || nb != 48 ) exit 1
                    for ( k in r ) {
                        if ( !(k in s) ) exit 1
                        d = r[k] - s[k]; if ( d < 0 ) d = -d; if ( d > dmax ) dmax = d
                        a = r[k]; if ( a < 0 ) a = -a; if ( a > scale ) scale = a
                    }
                    printf "     weights x %s: max |reaction difference| = %.2e\n", f, dmax
                    exit !(scale > 0.1 && dmax <= 1e-9 * scale)
                }' && echo "OK   weights x $factor: the same reactions" || fail "weights x $factor: the reactions change"
    else
        fail "weights x $factor: must run"
        cat "s3d-$factor.log"
    fi
done

# NURBS cylinder of radius 1 about y, one knot span of the quarter circle, membrane only, rigid translation
# (0.1, -0.2, 0.3); numexp 4 gives 4 x 4 VTK points, which must lie on x^2 + z^2 = 1 before the translation.
CYLINDER='nurbs3dsurfaceelement 1 nodes 6 1 2 3 4 5 6 crosssect 1 knotvectoru 2 0.0 1.0 knotvectorv 2 0.0 1.0 degree 2 1 2 nip 9 nlgeo 1 numexp 4 weights 6 1.0 1.0 0.7071067811865476 0.7071067811865476 1.0 1.0'
# $1 case name, $2 element record, $3 vtkxml record or empty
write_cylinder() {
    nmodules=0
    [ -n "$3" ] && nmodules=1
    cat > "$1.in" <<EOF
$1.out
NURBS cylinder (generated by iga-nurbs-axisym-checks.sh)
StaticStructural nsteps 1 deltat 1.0 rtolv 1.e-11 maxiter 10 nmodules $nmodules
$3
domain 3d
OutputManager tstep_all dofman_all
ndofman 6 nelem 1 ncrosssect 1 nmat 1 nbc 3 nic 0 nltf 1 nset 1
node 1 coords 3 1.0 0.0 0.0
node 2 coords 3 1.0 1.0 0.0
node 3 coords 3 1.0 0.0 1.0
node 4 coords 3 1.0 1.0 1.0
node 5 coords 3 0.0 0.0 1.0
node 6 coords 3 0.0 1.0 1.0
$2
simplesurfacecs 1 material 1
surfacetensionmat 1 gamma1 0.5 mu 1.0 d 1.0
BoundaryCondition 1 loadTimeFunction 1 dofs 1 1 values 1 0.1 set 1
BoundaryCondition 2 loadTimeFunction 1 dofs 1 2 values 1 -0.2 set 1
BoundaryCondition 3 loadTimeFunction 1 dofs 1 3 values 1 0.3 set 1
ConstantFunction 1 f(t) 1.0
Set 1 nodes 6 1 2 3 4 5 6
EOF
}

write_cylinder cylinder "$CYLINDER" 'vtkxml tstep_all domain_all primvars 1 1 stype 1'
if run_ok cylinder && vtu=$(ls cylinder.out.m*.1.vtu 2> /dev/null | head -1) && [ -n "$vtu" ]; then
    awk -v num='^[+-]?([0-9]+([.][0-9]*)?|[.][0-9]+)([eE][+-]?[0-9]+)?$' '
        /<Points>/ { points = 1; next }
        /<\/Points>/ { points = 0 }
        points && /<DataArray/ {
            sub(/^[^>]*>/, ""); sub(/<.*$/, "")
            n = split($0, v, " ")
            for ( i = 1; i <= n; i++ ) { if ( v[i] !~ num ) bad = 1; c[++m] = v[i] }
        }
        END {
            if ( bad || m != 48 ) exit 1
            for ( p = 0; p < 16; p++ ) {
                x = c[3 * p + 1]; z = c[3 * p + 3]
                d = x * x + z * z - 1; if ( d < 0 ) d = -d
                if ( d > 1e-6 ) exit 1  # vtkxml writes 7 significant digits
            }
        }' "$vtu" && echo "OK   cylinder: 16 VTK points on the circle" || fail "cylinder: VTK points not on the circle"
else
    fail "cylinder: should run and write a .vtu file"
    cat cylinder.log
fi

write_cylinder no-weights "${CYLINDER% weights *}"
expect_error no-weights 'weights'
write_cylinder weight-count "${CYLINDER% weights *} weights 5 1.0 1.0 0.7071067811865476 0.7071067811865476 1.0"
expect_error weight-count 'the number of weights must equal the number of control points'
write_cylinder zero-weight "${CYLINDER% weights *} weights 6 1.0 1.0 0.0 0.7071067811865476 1.0 1.0"
expect_error zero-weight 'weights must be finite and positive'
write_cylinder weight-ratio "${CYLINDER% weights *} weights 6 1e300 1e300 1e-10 1e-10 1e300 1e300"
expect_error weight-ratio 'the ratio of the smallest to the largest weight is below the range of double'

[ "$failures" -eq 0 ]
