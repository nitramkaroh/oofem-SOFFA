#
# Input checks of the planar IGA curve (BSpline2dLineInterpolation) of the IGA surface elements:
# - the bending material needs C1 continuity, so an interior knot of multiplicity p (C0, a kink) must be rejected
#   with bending and accepted for a membrane; the default multiplicity 1 (C1 for p = 2) must run with bending;
# - coinciding control points (zero tangent) must stop with an error instead of giving NaN;
# - a curve needs degree >= 1 and finite knot values;
# - the IGA surface elements implement only nlgeo 1.
# The inputs are generated into a temporary directory, so nothing is written to tests/sm.
# All displacements are prescribed; the material is evaluated for the reactions.
# Run by ctest as: bash iga-curve-checks.sh <oofem executable>
#
OOFEM=$1
case "$OOFEM" in
    /* | ?:*) ;;
    *) OOFEM="$PWD/$OOFEM" ;;
esac
echo "target executable: $OOFEM"

WORK=$(mktemp -d) || exit 1
trap 'cd / && rm -rf "$WORK"' EXIT
cd "$WORK" || exit 1

# Nodes 1-5 on the x axis, node 6 coincides with node 1. Unused nodes only carry the prescribed displacements.
C0='bsplineplanestrainsurfaceelement 1 nodes 5 1 2 3 4 5 crosssect 1 knotvectoru 3 0 0.5 1 knotmultiplicityu 3 3 2 3 degree 1 2 nip 3 nlgeo 1'
C1='bsplineplanestrainsurfaceelement 1 nodes 4 1 2 4 5 crosssect 1 knotvectoru 3 0 0.5 1 degree 1 2 nip 3 nlgeo 1'
COINCIDENT='bsplineplanestrainsurfaceelement 1 nodes 2 1 6 crosssect 1 knotvectoru 2 0 1 degree 1 1 nip 2 nlgeo 1'
DEGREE0='bsplineplanestrainsurfaceelement 1 nodes 1 1 crosssect 1 knotvectoru 2 0 1 degree 1 0 nip 1 nlgeo 1'
NANKNOT='bsplineplanestrainsurfaceelement 1 nodes 2 1 5 crosssect 1 knotvectoru 2 0 nan degree 1 1 nip 2 nlgeo 1'
NLGEO0='bsplineplanestrainsurfaceelement 1 nodes 4 1 2 4 5 crosssect 1 knotvectoru 3 0 0.5 1 degree 1 2 nip 3'
BENDING='surfacetensionmat2 1 gamma1 0.5 omega1 1.0 d 1.0'
MEMBRANE='surfacetensionmat 1 gamma1 0.5 d 1.0'

# $1 case name, $2 element record, $3 material record
write_input() {
    cat > "$1.in" <<EOF
$1.out
IGA curve checks: $2 / $3 (generated by iga-curve-checks.sh)
StaticStructural nsteps 1 deltat 1.0 rtolv 1.e-11 maxiter 10 nmodules 0
domain 2dPlaneStress
OutputManager tstep_all dofman_all element_all
ndofman 6 nelem 1 ncrosssect 1 nmat 1 nbc 3 nic 0 nltf 1 nset 3
node 1 coords 2 0.0 0.0
node 2 coords 2 0.25 0.0
node 3 coords 2 0.5 0.0
node 4 coords 2 0.75 0.0
node 5 coords 2 1.0 0.0
node 6 coords 2 0.0 0.0
$2
simplesurfacecs 1 material 1
$3
BoundaryCondition 1 loadTimeFunction 1 dofs 1 1 values 1 0.0 set 1
BoundaryCondition 2 loadTimeFunction 1 dofs 1 2 values 1 0.0 set 2
BoundaryCondition 3 loadTimeFunction 1 dofs 1 2 values 1 0.1 set 3
ConstantFunction 1 f(t) 1.0
Set 1 nodes 6 1 2 3 4 5 6
Set 2 nodes 5 1 2 3 4 6
Set 3 nodes 1 5
EOF
}

failures=0

# The analysis must finish and give no NaN.
expect_run() {
    write_input "$1" "$2" "$3"
    if ! "$OOFEM" -f "$1.in" > "$1.log" 2>&1; then
        echo "FAIL $1: should run"
        cat "$1.log"
        failures=$((failures + 1))
    elif grep -qi 'nan' "$1.out"; then
        echo "FAIL $1: runs, but gives NaN"
        failures=$((failures + 1))
    else
        echo "OK   $1: runs"
    fi
}

# The analysis must stop with an error containing $4.
expect_error() {
    write_input "$1" "$2" "$3"
    if "$OOFEM" -f "$1.in" > "$1.log" 2>&1; then
        echo "FAIL $1: must be rejected, but the analysis finished"
        failures=$((failures + 1))
    elif grep -q "$4" "$1.log"; then
        echo "OK   $1: rejected"
    else
        echo "FAIL $1: failed for another reason"
        cat "$1.log"
        failures=$((failures + 1))
    fi
}

expect_error c0-bending        "$C0"         "$BENDING"  'second gradient'
expect_run   c0-membrane       "$C0"         "$MEMBRANE"
expect_run   c1-bending        "$C1"         "$BENDING"
expect_error coincident-points "$COINCIDENT" "$MEMBRANE" 'degenerate curve'
expect_error degree0           "$DEGREE0"    "$MEMBRANE" 'degree >= 1'
expect_error nan-knot          "$NANKNOT"    "$MEMBRANE" 'must be finite'
expect_error nlgeo-zero        "$NLGEO0"     "$MEMBRANE" 'only nlgeo 1'

[ "$failures" -eq 0 ]
