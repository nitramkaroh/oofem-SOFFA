#
# VTK export (vtkxml) of the IGA elements, IGAElement::giveCompositeExportData:
# - a two-span quadratic surface curve and a bilinear bulk patch (numexp 3) under the rigid translation
#   (0.1, -0.2): the numbers of points and cells, the cell types, the end positions and the displacement
#   (0.1, -0.2, 0) at every export point;
# - the curvature tensor of the bending curve is written row by row (11 12 13 21 22 23 31 32 33): the
#   inclined curve has K12 = K21 (components 2 and 4) nonzero, and the out-of-plane components are zero
#   (the Voigt order 11 22 33 23 13 12 32 31 21 would put K22 at component 2 and K23 = 0 at component 4);
# - unsupported requests stop with an error: an internal variable other than the curvature, cell
#   variables, and the curvature of a membrane material (only the bending materials store it).
# The inputs are generated into a temporary directory, so nothing is written to tests/sm.
# Run by ctest as: bash iga-vtk-export.sh <oofem executable>
#
OOFEM=$1
case "$OOFEM" in
    /* | ?:*) ;;
    *) OOFEM="$PWD/$OOFEM" ;;
esac
echo "target executable: $OOFEM"

WORK=$(mktemp -d) || exit 1
trap 'cd / && rm -rf "$WORK"' EXIT
cd "$WORK" || exit 1

CURVE='bsplineplanestrainsurfaceelement 1 nodes 4 1 2 3 4 crosssect 1 knotvectoru 3 0 0.5 1 degree 1 2 nip 2 nlgeo 1 numexp 3'
PATCH='bsplineplanestrainelement 1 nodes 4 1 2 3 4 crosssect 1 knotvectoru 2 0 1 knotvectorv 2 0 1 degree 2 1 1 nip 4 nlgeo 0 numexp 3'
BENDING='surfacetensionmat2 1 gamma1 0.5 omega1 1.0 d 1.0'
MEMBRANE='surfacetensionmat 1 gamma1 0.5 d 1.0'

# $1 case name, $2 vtkxml record, $3 element record, $4 cross section and material records, $5 node records
write_input() {
    cat > "$1.in" <<EOF
$1.out
IGA VTK export check (generated by iga-vtk-export.sh)
StaticStructural nsteps 1 deltat 1.0 rtolv 1.e-11 maxiter 10 nmodules 1
$2
domain 2dPlaneStress
OutputManager tstep_all dofman_all
ndofman 4 nelem 1 ncrosssect 1 nmat 1 nbc 2 nic 0 nltf 1 nset 1
$5
$3
$4
BoundaryCondition 1 loadTimeFunction 1 dofs 1 1 values 1 0.1 set 1
BoundaryCondition 2 loadTimeFunction 1 dofs 1 2 values 1 -0.2 set 1
ConstantFunction 1 f(t) 1.0
Set 1 nodes 4 1 2 3 4
EOF
}

CURVE_NODES='node 1 coords 2 0.0 0.0
node 2 coords 2 0.3 0.5
node 3 coords 2 0.7 0.6
node 4 coords 2 1.0 0.0'
PATCH_NODES='node 1 coords 2 0.0 0.0
node 2 coords 2 1.0 0.0
node 3 coords 2 0.0 1.0
node 4 coords 2 1.0 1.0'

failures=0
fail() {
    echo "FAIL $1"
    failures=$((failures + 1))
}

# Values of the data array whose opening tag contains $2 (one array per line, as vtkxml writes it), one per line.
array() {
    awk -v key="$2" 'index($0, key) { sub(/^[^>]*>/, ""); sub(/<.*$/, ""); n = split($0, v, " "); for ( i = 1; i <= n; i++ ) print v[i] }' "$1"
}

# Runs case $1; the analysis must finish and write one .vtu file, whose name is printed.
run_vtu() {
    if ! "$OOFEM" -f "$1.in" > "$1.log" 2>&1; then
        fail "$1: should run"
        cat "$1.log"
        return 1
    fi
    vtu=$(ls "$1".out.m*.1.vtu 2> /dev/null | head -1)
    if [ -z "$vtu" ]; then
        fail "$1: no .vtu written"
        return 1
    fi
    echo "$vtu"
}

# Case $1 must write a piece with $2 points and $3 cells of the VTK type $4, the first point at ($5, $6), the
# last at ($7, $8), and the displacement (0.1, -0.2, 0) at every point.
check_geometry() {
    vtu=$(run_vtu "$1") || return
    grep -q "NumberOfPoints=\"$2\" NumberOfCells=\"$3\"" "$vtu" || fail "$1: expected $2 points and $3 cells"
    array "$vtu" 'Name="types"' | awk -v t="$4" '$1 != t { bad = 1 } END { exit bad }' || fail "$1: cell types are not all $4"
    array "$vtu" 'NumberOfComponents="3" format="ascii"' | head -n $((3 * $2)) |
        awk -v n="$2" -v x1="$5" -v y1="$6" -v xn="$7" -v yn="$8" '
            { c[NR] = $1 }
            END {
                if ( NR != 3 * n ) exit 1
                d = (c[1] - x1)^2 + (c[2] - y1)^2 + c[3]^2 + (c[3*n-2] - xn)^2 + (c[3*n-1] - yn)^2 + c[3*n]^2
                exit d > 1e-20
            }' || fail "$1: positions of the first or last point"
    array "$vtu" 'Name="DisplacementVector"' |
        awk -v n="$2" '{ e = (NR % 3 == 1) ? 0.1 : (NR % 3 == 2) ? -0.2 : 0.; if ( ($1 - e)^2 > 1e-24 ) bad = 1 }
                       END { exit bad || NR != 3 * n }' || fail "$1: displacement differs from (0.1, -0.2, 0)"
    echo "OK   $1: $2 points, $3 cells, positions and displacements"
}

# The curvature of case $1 must have 9 components per point, row by row, symmetric in the plane of the curve.
check_curvature() {
    vtu=$(run_vtu "$1") || return
    array "$vtu" 'Name="IST_CurvatureTensor"' |
        awk -v n="$2" '
            { k[(NR - 1) % 9 + 1] = $1 }
            NR % 9 == 0 {
                if ( (k[2] - k[4])^2 > 1e-24 ) bad = 1        # K12 = K21
                if ( k[3]^2 + k[6]^2 + k[7]^2 + k[8]^2 + k[9]^2 > 1e-24 ) bad = 1  # no out-of-plane part
                if ( k[2]^2 > 1e-6 ) inclined = 1           # K12 != 0 somewhere
            }
            END { exit bad || !inclined || NR != 9 * n }' || { fail "$1: curvature tensor is not written row by row"; return; }
    echo "OK   $1: curvature written row by row"
}

# Case $1 must stop with an error containing $2.
expect_error() {
    if "$OOFEM" -f "$1.in" > "$1.log" 2>&1; then
        fail "$1: must be rejected, but the analysis finished"
    elif grep -q "$2" "$1.log"; then
        echo "OK   $1: rejected"
    else
        fail "$1: failed for another reason"
        cat "$1.log"
    fi
}

VTK_DISP='vtkxml tstep_all domain_all primvars 1 1 stype 1'
VTK_CURV='vtkxml tstep_all domain_all primvars 1 1 vars 1 11 stype 1'
VTK_STRESS='vtkxml tstep_all domain_all primvars 1 1 vars 1 1 stype 1'
VTK_CELL='vtkxml tstep_all domain_all primvars 1 1 cellvars 1 1 stype 1'
SURFACE_CS='simplesurfacecs 1 material 1'
BULK_CS="simplecs 1 thick 1.0 material 1
isole 1 d 1.0 e 1.0 n 0.2 talpha 0.0"

write_input curve "$VTK_DISP" "$CURVE" "$SURFACE_CS
$BENDING" "$CURVE_NODES"
check_geometry curve 6 4 3 0.0 0.0 1.0 0.0

write_input patch "$VTK_DISP" "$PATCH" "$BULK_CS" "$PATCH_NODES"
check_geometry patch 9 4 9 0.0 0.0 1.0 1.0

write_input curvature "$VTK_CURV" "$CURVE" "$SURFACE_CS
$BENDING" "$CURVE_NODES"
check_curvature curvature 6

write_input stress "$VTK_STRESS" "$CURVE" "$SURFACE_CS
$BENDING" "$CURVE_NODES"
expect_error stress 'is not supported by the VTK export'

write_input cellvars "$VTK_CELL" "$CURVE" "$SURFACE_CS
$BENDING" "$CURVE_NODES"
expect_error cellvars 'cell variables are not supported'

write_input membrane-curvature "$VTK_CURV" "$CURVE" "$SURFACE_CS
$MEMBRANE" "$CURVE_NODES"
expect_error membrane-curvature 'computed only by the bending surface materials'

[ "$failures" -eq 0 ]
